package wealthsei.report;

import wealthsei.domain.SavingsGoal;

/** Markdown: headings, a bullet summary and a table. */
public class MarkdownExporter extends ReportExporter {

    @Override
    protected String writeHeader(ReportData data) {
        return "# WealthSei report: " + data.month() + "\n\n";
    }

    @Override
    protected String writeSummary(ReportData data) {
        StringBuilder sb = new StringBuilder("## Summary\n\n");
        sb.append("- Money in: ").append(data.income()).append('\n');
        sb.append("- Money out: ").append(data.spending()).append('\n');
        sb.append("- Net: ").append(data.net()).append('\n');
        sb.append("- Transactions: ").append(data.transactionCount()).append("\n\n");
        sb.append("### Goals\n\n");
        if (data.goals().isEmpty()) {
            sb.append("No savings goals.\n\n");
        } else {
            for (SavingsGoal g : data.goals()) {
                sb.append("- ").append(g.name()).append(": ").append(g.saved()).append(" of ").append(g.target())
                        .append(" by ").append(g.deadline()).append(" (").append(g.status()).append(")\n");
            }
            sb.append('\n');
        }
        return sb.toString();
    }

    @Override
    protected String writeCategoryTable(ReportData data) {
        StringBuilder sb = new StringBuilder("## Spending by category\n\n");
        if (data.categories().isEmpty()) {
            return sb.append("No spending this month.\n\n").toString();
        }
        sb.append("| Category | Spent | Limit | Remaining | Status |\n|---|---:|---:|---:|---|\n");
        for (ReportData.CategoryRow r : data.categories()) {
            sb.append("| ").append(r.category().name()).append(" | ").append(r.spent()).append(" | ")
                    .append(r.limit().map(Object::toString).orElse("-")).append(" | ")
                    .append(r.remaining().map(Object::toString).orElse("-")).append(" | ")
                    .append(r.level().map(Enum::name).orElse("no budget")).append(" |\n");
        }
        return sb.append('\n').toString();
    }

    @Override
    protected String writeReviewSection(ReportData data) {
        StringBuilder sb = new StringBuilder("## Monthly review\n\n");
        if (data.review().isEmpty()) {
            return sb.append('*').append(noReviewNote(data)).append("*\n\n").toString();
        }
        var review = data.review().get();
        sb.append("Health score: ").append(review.healthScore().total()).append("/100\n\n");
        sb.append(review.narrative()).append("\n\n");
        return sb.toString();
    }

    @Override
    protected String writeFooter(ReportData data) {
        return "---\nGenerated by WealthSei on " + data.generatedOn() + ".\n";
    }
}
