package wealthsei.report;

import wealthsei.domain.SavingsGoal;

/** Plain text with aligned columns, readable in any editor or email. */
public class TextExporter extends ReportExporter {

    @Override
    protected String writeHeader(ReportData data) {
        String title = "WealthSei report: " + data.month();
        return title + "\n" + "=".repeat(title.length()) + "\n\n";
    }

    @Override
    protected String writeSummary(ReportData data) {
        StringBuilder sb = new StringBuilder("SUMMARY\n");
        sb.append(String.format("  %-14s %12s%n", "Money in", data.income()));
        sb.append(String.format("  %-14s %12s%n", "Money out", data.spending()));
        sb.append(String.format("  %-14s %12s%n", "Net", data.net()));
        sb.append(String.format("  %-14s %12d%n%n", "Transactions", data.transactionCount()));
        sb.append("GOALS\n");
        if (data.goals().isEmpty()) {
            sb.append("  No savings goals.\n");
        }
        for (SavingsGoal g : data.goals()) {
            sb.append(String.format("  %s: %s of %s by %s (%s)%n", g.name(), g.saved(), g.target(), g.deadline(), g.status()));
        }
        return sb.append('\n').toString();
    }

    @Override
    protected String writeCategoryTable(ReportData data) {
        StringBuilder sb = new StringBuilder("SPENDING BY CATEGORY\n");
        if (data.categories().isEmpty()) {
            return sb.append("  No spending this month.\n\n").toString();
        }
        sb.append(String.format("  %-16s %10s %10s %10s  %s%n", "Category", "Spent", "Limit", "Remaining", "Status"));
        for (ReportData.CategoryRow r : data.categories()) {
            sb.append(String.format("  %-16s %10s %10s %10s  %s%n", r.category().name(), r.spent(),
                    r.limit().map(Object::toString).orElse("-"), r.remaining().map(Object::toString).orElse("-"),
                    r.level().map(Enum::name).orElse("no budget")));
        }
        return sb.append('\n').toString();
    }

    @Override
    protected String writeReviewSection(ReportData data) {
        StringBuilder sb = new StringBuilder("MONTHLY REVIEW\n");
        if (data.review().isEmpty()) {
            return sb.append("  ").append(noReviewNote(data)).append("\n\n").toString();
        }
        var review = data.review().get();
        sb.append("  Health score: ").append(review.healthScore().total()).append("/100\n\n");
        for (String line : review.narrative().split("\\R")) {
            sb.append("  ").append(line).append('\n');
        }
        return sb.append('\n').toString();
    }

    @Override
    protected String writeFooter(ReportData data) {
        return "Generated by WealthSei on " + data.generatedOn() + ".\n";
    }
}
