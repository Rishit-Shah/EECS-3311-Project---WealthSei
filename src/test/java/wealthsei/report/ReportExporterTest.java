package wealthsei.report;

import static org.junit.jupiter.api.Assertions.*;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Instant;
import java.time.LocalDate;
import java.time.YearMonth;
import java.util.List;
import java.util.Optional;
import org.junit.jupiter.api.Test;
import wealthsei.domain.AlertSeverity;
import wealthsei.domain.Categories;
import wealthsei.domain.GoalStatus;
import wealthsei.domain.HealthScore;
import wealthsei.domain.MonthlyReview;
import wealthsei.domain.Money;
import wealthsei.domain.SavingsGoal;

class ReportExporterTest {

    private static final YearMonth MONTH = YearMonth.of(2026, 10);

    private static ReportData data(Optional<MonthlyReview> review) {
        return new ReportData(MONTH, LocalDate.of(2026, 11, 5), Money.of("2000"), Money.of("350.50"), 12,
                List.of(new ReportData.CategoryRow(Categories.DINING, Money.of("250.50"), Optional.of(Money.of("200")),
                                Optional.of(AlertSeverity.OVER)),
                        new ReportData.CategoryRow(Categories.TRANSPORT, Money.of("100"), Optional.empty(), Optional.empty())),
                List.of(new SavingsGoal("g1", "Laptop, 14\"", Money.of("1200"), LocalDate.of(2027, 1, 1), Money.of("100"),
                        Money.of("50"), GoalStatus.ON_TRACK)),
                review);
    }

    private static MonthlyReview review() {
        return new MonthlyReview(MONTH, new HealthScore(72, List.of(), List.of(), "ok", null),
                "Dining went over.\nTry a cap.", List.of(), "t1", Instant.parse("2026-11-05T12:00:00Z"));
    }

    private static Path out(String ext) throws IOException {
        Path p = Files.createTempFile("wealthsei-report", "." + ext);
        Files.delete(p);
        p.toFile().deleteOnExit();
        return p;
    }

    @Test
    void markdownHasTheFiveSectionsInOrder() throws IOException {
        Path p = new MarkdownExporter().export(data(Optional.of(review())), out("md"));
        String text = Files.readString(p);
        int header = text.indexOf("# WealthSei report: 2026-10");
        int summary = text.indexOf("## Summary");
        int table = text.indexOf("## Spending by category");
        int rev = text.indexOf("## Monthly review");
        int footer = text.indexOf("Generated by WealthSei on 2026-11-05");
        assertTrue(header >= 0 && header < summary && summary < table && table < rev && rev < footer, text);
        assertTrue(text.contains("| Dining out | 250.50 | 200.00 | -50.50 | OVER |"), text);
        assertTrue(text.contains("| Transport | 100.00 | - | - | no budget |"), text);
        assertTrue(text.contains("Net: 1649.50"), text);
        assertTrue(text.contains("Dining went over."), text);
        assertTrue(text.contains("72/100"), text);
    }

    @Test
    void withoutAReviewEveryFormatSaysSo() throws IOException {
        for (ReportExporter e : List.of(new MarkdownExporter(), new TextExporter(), new CsvExporter())) {
            String text = Files.readString(e.export(data(Optional.empty()), out("x")));
            assertTrue(text.contains("No monthly review has been generated for 2026-10"), text);
            assertFalse(text.contains("Dining went over."));
        }
    }

    @Test
    void textReportIsAlignedPlainText() throws IOException {
        String text = Files.readString(new TextExporter().export(data(Optional.of(review())), out("txt")));
        assertTrue(text.startsWith("WealthSei report: 2026-10"), text);
        assertTrue(text.contains("SPENDING BY CATEGORY"), text);
        assertTrue(text.contains("Dining out"), text);
        assertTrue(text.contains("  Dining went over."), text);
        assertTrue(text.contains("Try a cap."), text);
    }

    @Test
    void csvIsOneTableAndQuotesAwkwardText() throws IOException {
        String text = Files.readString(new CsvExporter().export(data(Optional.of(review())), out("csv")));
        List<String> lines = text.lines().toList();
        assertEquals("section,name,amount,limit,remaining,status", lines.get(0));
        assertTrue(text.contains("category,Dining out,250.50,200.00,-50.50,OVER"), text);
        assertTrue(text.contains("category,Transport,100.00,,,NO_BUDGET"), text);
        assertTrue(text.contains("\"Laptop, 14\"\"\""), text);
        assertTrue(text.contains("\"Dining went over.\nTry a cap.\""), text);
        assertTrue(text.contains("footer,generated_on,2026-11-05"), text);
    }

    @Test
    void csvEscapingRules() {
        assertEquals("plain", CsvExporter.escape("plain"));
        assertEquals("\"a,b\"", CsvExporter.escape("a,b"));
        assertEquals("\"say \"\"hi\"\"\"", CsvExporter.escape("say \"hi\""));
    }

    @Test
    void aMissingFolderIsAnExportException() {
        Path bad = Path.of("/this/folder/does/not/exist/report.md");
        ExportException e = assertThrows(ExportException.class, () -> new MarkdownExporter().export(data(Optional.empty()), bad));
        assertTrue(e.getMessage().contains("does not exist"));
    }

    @Test
    void anEmptyMonthStillProducesAReadableReport() throws IOException {
        ReportData empty = new ReportData(MONTH, LocalDate.of(2026, 11, 5), Money.ZERO, Money.ZERO, 0, List.of(), List.of(),
                Optional.empty());
        String text = Files.readString(new MarkdownExporter().export(empty, out("md")));
        assertTrue(text.contains("No spending this month.") && text.contains("No savings goals."), text);
    }

    @Test
    void netIsIncomeMinusSpending() {
        assertEquals(Money.of("1649.50"), data(Optional.empty()).net());
        assertTrue(data(Optional.empty()).hasBudget());
    }
}
